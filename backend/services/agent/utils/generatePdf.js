import PDFDocument from "pdfkit";

export const generatePdf = async (data) => {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({
      size: "A4",
      margin: 50,
      info: {
        Author: "AvioraAI",
        Title: data.title,
        Creator: "AvioraAI",
      },
    });

    // data ayega, chote chote chunks mei ayega toh hum is array mei push krdenge
    const chunks = [];
    // chunks concatenanted
    doc.on("data", (chunk) => chunks.push(chunk));
    // when document end , promise response resloved and buffer concatenated & send
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    // reject promise if error comes
    doc.on("error", reject);

    // data dalna hai document mei

    //title dala
    doc
      .fontSize(28)
      .text(data.title, {
        align: "center"
      })
      .fillColor("#111827");

    if (data.subtitle) {
      doc.moveDown(0.5);
    }

    //subtitle dala
    doc
      .fontSize(12)
      .text(data.subtitle, {
        align: "center",
      })
      .fillColor("#6B7280");

    doc.moveDown(2);

    // sections

    data?.sections?.forEach((s) => {
      doc.fontSize(18).text(s.heading).fillColor("#111827");

      doc.moveDown(0.5);

      s?.points?.forEach((p) => {
        doc
          .fontSize(12)
          .text("• " + p, {
            lineGap: 5,
          })
          .fillColor("#374151");
      });
      doc.moveDown();
    });
    doc.moveDown();

    //footer
    doc
      .fontSize(10)
      .text("Generated by AvioraAI", {
        align: "center",
      })
      .fillColor("#9CA3AF");

      doc.end()
  });
};
